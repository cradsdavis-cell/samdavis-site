// scripts/syndicate.mjs - an essay page's body as plain, portable HTML for other
// platforms (the full-text RSS feed, which Substack imports, and the paste-ready
// LinkedIn newsletter / Substack copies Idris builds from that feed).
//
//   import { essayBody, figureSnaps, syndicationHtml } from './syndicate.mjs'
//
// Other platforms strip classes, CSS variables and inline SVG, so:
//   - every figure that is not a photo (SVG diagrams, HTML chart cards) is swapped
//     for its PNG snapshot, writing/<slug>/fig-<n>.png (n counts those figures in
//     page order, from 1); scripts/snap-figures.mjs makes the PNGs from the live page
//   - relative links and image paths become absolute https://crads-ai.com URLs
//   - classes, ids, inline styles and lazy-loading attributes are dropped
//   - the collapsible references become a plain "Sources" list, and in-page citation
//     links (#ref-...) keep their text only
//   - the drafting note leads and a "first published at" line closes (the note is
//     required wherever an essay appears: public-copy-claims)
// Regex-based on purpose: the essay pages are generated by scripts/build-essay-*.py
// with one fixed markup, and tests/syndicate.test.js pins the result for every essay.

export const HOST = 'https://crads-ai.com';
export const DRAFTING_NOTE = 'Built from my own ideas and stories, with Claude as a drafting partner.';

export function essayBody(src, rel = 'page') {
  const m = src.match(/<article class="essay-body">([\s\S]*?)<\/article>/);
  if (!m) throw new Error(`${rel}: no essay-body`);
  return m[1];
}

const absolute = (html) => html.replace(/\b(href|src)="\/(?!\/)/g, `$1="${HOST}/`);

const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : null;
};

// The figures in an essay that need a PNG snapshot (no <img> inside), in page order.
export function figureSnaps(body) {
  const out = [];
  for (const m of body.matchAll(/<figure\b([^>]*)>([\s\S]*?)<\/figure>/g)) {
    if (/<img\b/.test(m[2])) continue;
    out.push({ n: out.length + 1, label: attr(`<x${m[1]}>`, 'aria-label') || '' });
  }
  return out;
}

export function syndicationHtml(src, { slug, url, rel = slug } = {}) {
  let body = essayBody(src, rel);

  // References: <section class="essay-refs"><details>...<ul>..</ul></details></section> -> Sources list.
  body = body.replace(/<section class="essay-refs"[\s\S]*?<\/section>/, (sec) => {
    const lists = [...sec.matchAll(/<h3>([^<]*)<\/h3>\s*(<ul>[\s\S]*?<\/ul>)/g)];
    return lists.map(([, h, ul]) => `<h3>${h}</h3>\n${ul.replace(/<li id="[^"]*">/g, '<li>')}`).join('\n');
  });

  // Figures: photos keep their images; everything else becomes its PNG snapshot.
  let snap = 0;
  body = body.replace(/<figure\b([^>]*)>([\s\S]*?)<\/figure>/g, (_, open, inner) => {
    const cap = (inner.match(/<figcaption>([\s\S]*?)<\/figcaption>/) || [])[1];
    const caption = cap ? `<figcaption>${cap.trim()}</figcaption>` : '';
    const imgs = [...inner.matchAll(/<img\b[^>]*>/g)].map(([tag]) => {
      const alt = attr(tag, 'alt') || '';
      return `<img src="${attr(tag, 'src')}" alt="${alt}">`;
    });
    if (imgs.length) return `<figure>${imgs.join('')}${caption}</figure>`;
    snap += 1;
    const alt = (attr(`<x${open}>`, 'aria-label') || '').replace(/^(Diagram|Figure|Chart):\s*/i, '');
    return `<figure><img src="/writing/${slug}/fig-${snap}.png" alt="${alt}">${caption}</figure>`;
  });

  // In-page citation links (#ref-...) point at ids the copy doesn't carry: keep the text.
  body = body.replace(/<a\b[^>]*href="#[^"]*"[^>]*>([\s\S]*?)<\/a>/g, '$1');

  body = body
    .replace(/<(h[1-6]|p|ul|ol|li|a|em|strong|blockquote|span)\b([^>]*)>/g, (_, tag, attrs) => {
      const keep = ['href', 'target', 'rel'].map((n) => {
        const v = attr(`<x${attrs}>`, n);
        return v === null ? '' : ` ${n}="${v}"`;
      }).join('');
      return `<${tag}${keep}>`;
    })
    .replace(/<\/?span>/g, '')
    .replace(/\n{2,}/g, '\n')
    .trim();

  const head = `<p><em>${DRAFTING_NOTE}</em></p>`;
  const tail = `<p><em>First published at <a href="${url}">crads-ai.com</a>.</em></p>`;
  return absolute(`${head}\n${body}\n${tail}`);
}
