// scripts/build-newsletter-index.mjs - writes newsletter/index.html, the home of
// Restless Optimist (Sam's weekly letter, "The Crads-AI letter" until 3 Nov 2026):
// the name and the sign-up, the newest issue in full, then every issue.
//   npm run newsletter   (then npm run sitemap && npm run llms)
// Issues are the web copies at newsletter/<N>/index.html, written by the
// second brain's cockpit/tools/newsletter/web.mjs, which stamps each <main>
// with data-issue, data-date and data-subject. tests/newsletterIndex.test.js
// fails when this page is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const { navHTML, footerHTML } = createRequire(import.meta.url)('../lib/site.js');

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'newsletter');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unesc = (s) => String(s).replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

export function readIssues() {
  return fs.readdirSync(DIR)
    .filter((n) => /^\d+$/.test(n) && fs.existsSync(path.join(DIR, n, 'index.html')))
    .map((n) => {
      const html = fs.readFileSync(path.join(DIR, n, 'index.html'), 'utf8');
      const main = html.match(/<main class="newsletter-web"([^>]*)>([\s\S]*?)<\/main>/);
      if (!main) throw new Error(`newsletter/${n}: no <main class="newsletter-web">`);
      const attr = (k) => { const m = main[1].match(new RegExp(`data-${k}="([^"]*)"`)); return m ? unesc(m[1]) : ''; };
      const style = (html.match(/<style>([\s\S]*?)<\/style>/) || [])[1] || '';
      const desc = (html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
      return { number: Number(n), date: attr('date'), subject: attr('subject'), desc: unesc(desc), body: main[2].trim(), style };
    })
    .sort((a, b) => b.number - a.number);
}

export function renderIndex(issues) {
  const [latest] = issues;
  const title = 'Restless Optimist · Sam Davis’s weekly letter';
  const desc = 'Restless Optimist, Sam Davis’s weekly letter: one essay and three bits of AI news worth your time, every Thursday. Read the latest issue and the archive, or sign up.';
  const archive = issues.map((i) => [
    '        <li>',
    `          <a href="/newsletter/${i.number}">`,
    `            <span class="letter-no">No. ${i.number}</span>`,
    `            <span class="letter-subject">${esc(i.subject)}</span>`,
    `            <span class="letter-date">${esc(i.date)}</span>`,
    '          </a>',
    '        </li>',
  ].join('\n')).join('\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<link rel="icon" type="image/png" sizes="64x64" href="/lib/img/favicon.png">
<link rel="icon" type="image/x-icon" href="/lib/img/favicon.ico">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${title}</title>
<meta name="description" content="${esc(desc)}">
<link rel="stylesheet" href="/lib/site.css">
<script defer src="/lib/site.js"></script>
<link rel="canonical" href="https://crads-ai.com/newsletter">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Crads-AI">
<meta property="og:url" content="https://crads-ai.com/newsletter">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:image" content="https://crads-ai.com/lib/img/og-card.png">
<meta name="author" content="Sam Davis">
<!-- Generated by scripts/build-newsletter-index.mjs (npm run newsletter). Edit the script, not this file. -->
<style>${latest.style}</style>
</head>
<body>

${navHTML('/newsletter')}

<main class="letter-home">
  <header class="letter-hero wrap">
    <p class="eyebrow">The weekly letter</p>
    <h1>Restless Optimist</h1>
    <p class="letter-tagline">Exploring the edges of AI, business and adventure.</p>
    <p class="letter-what">Every Thursday: one essay and three bits of AI news worth your time, short enough to read over a coffee.</p>
    <div class="letter-signup"></div>
    <p class="letter-note">Booked a call with me? You’re already on the list: every booking adds you, and every issue has a one-click unsubscribe.</p>
  </header>

  <section class="letter-latest" aria-labelledby="latest-title">
    <div class="wrap">
      <h2 id="latest-title" class="letter-section-head">Latest issue <span>No. ${latest.number} · ${esc(latest.date)}</span></h2>
    </div>
    <div class="letter-issue newsletter-web">
${latest.body}
    </div>
  </section>

  <section class="letter-archive wrap" aria-labelledby="archive-title">
    <h2 id="archive-title" class="letter-section-head">Every issue</h2>
    <ol class="letter-list" reversed>
${archive}
    </ol>
  </section>
</main>

${footerHTML()}

</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(DIR, 'index.html');
  fs.writeFileSync(out, renderIndex(readIssues()));
  console.log('wrote newsletter/index.html');
}
